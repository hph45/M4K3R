import { readFile } from "node:fs/promises"
import { expect, test } from "@playwright/test"

test("PCB places real footprints, routes shared nets, checks copper and exports fabrication with undo/reload", async ({ page, request }, testInfo) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  const created = await request.post("/api/projects", { data: { name: "PCB browser verification" } }), project = await created.json()
  expect(created.ok()).toBe(true)
  const terminal = { id: "qa-terminal", name: "QA round terminal", refPrefix: "J", pins: [{ num: "1", name: "1", type: "passive" }], footprint: { source: "QA:Terminal", pads: [{ num: "1", type: "thru_hole", shape: "circle", at: [0, 0], size: [2, 2], drill: [0.8, 0.8], layers: ["*.Cu", "*.Mask"] }], graphics: [], courtyard: { min: [-2, -2], max: [2, 2] } } }
  const seeded = await request.post(`/api/projects/${project.id}/commands`, { data: { commands: [{ type: "part.vendor", args: { part: terminal } }, { type: "component.add", args: { part: terminal.id } }, { type: "component.add", args: { part: terminal.id } }, { type: "net.connect", args: { pins: ["J1.1", "J2.1"], name: "SIGNAL" } }] } })
  expect(seeded.ok()).toBe(true)
  await page.goto(`/#/p/${project.id}/wiring`)
  await page.getByRole("button", { name: "＋ New document", exact: true }).click()
  await page.getByText("New PCB…", { exact: true }).click()
  await page.getByPlaceholder("PCB name").fill("Carrier")
  await page.getByPlaceholder("PCB name").press("Enter")
  await expect(page.getByTestId("pcb-canvas")).toBeVisible()
  await expect(page.locator(".pcb-footprint")).toHaveCount(2)
  const before = await (await request.get(`/api/projects/${project.id}`)).json(), board = before.docs.find((d: { kind: string }) => d.kind === "pcb")
  const second = page.locator('.pcb-footprint[data-component-ref="J2"] polygon'), box = await second.boundingBox()
  expect(box).not.toBeNull()
  await page.mouse.move(box!.x + box!.width * .8, box!.y + box!.height * .2)
  await page.mouse.down(); await page.mouse.move(box!.x + box!.width * .8 + 35, box!.y + box!.height * .2 + 24, { steps: 8 }); await page.mouse.up()
  await expect.poll(async () => (await (await request.get(`/api/projects/${project.id}`)).json()).docs.find((d: { id: string }) => d.id === board.id).data.placements[1].at).not.toEqual(board.data.placements[1].at)
  await page.getByTitle(/^Undo Move PCB footprint/).click()
  await expect.poll(async () => (await (await request.get(`/api/projects/${project.id}`)).json()).docs.find((d: { id: string }) => d.id === board.id).data.placements[1].at).toEqual(board.data.placements[1].at)
  await page.getByRole("button", { name: "Route", exact: true }).click()
  await page.locator('[data-pad-address="J1.1"]').click()
  await page.locator('[data-pad-address="J2.1"]').click()
  await expect(page.locator(".pcb-track")).toHaveCount(1)
  await expect(page.locator(".pcb-inspector")).toContainText("All PCB checks pass.")
  const check = await request.get(`/api/projects/${project.id}/pcb/${board.id}/drc`)
  expect(await check.json()).toEqual([])
  await page.reload()
  await expect(page.locator(".pcb-track")).toHaveCount(1)
  await page.screenshot({ path: testInfo.outputPath("pcb-routed.png") })
  const download = page.waitForEvent("download")
  await page.getByRole("button", { name: "Fabrication ZIP", exact: true }).click()
  const fab = await download, bytes = await readFile((await fab.path())!)
  expect(bytes.subarray(0, 2).toString()).toBe("PK")
  for (const file of ["board-F_Cu.gbr", "board-PTH.drl", "BOM.csv", "PickAndPlace.csv", "Board.step"]) expect(bytes.includes(Buffer.from(file))).toBe(true)
  await page.getByRole("button", { name: "3D board", exact: true }).click()
  await expect(page.getByLabel(/^3D part viewport/)).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath("pcb-3d.png") })
  expect(errors).toEqual([])
})
