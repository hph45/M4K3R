import { expect,test } from "@playwright/test"

test("mechanical assembly places catalog and printed parts, mounts holes, configures families and exports",async({page,request},testInfo)=>{
  const errors:string[]=[];page.on("pageerror",error=>errors.push(error.message))
  const project=await(await request.post("/api/projects",{data:{name:"Mechanical acceptance"}})).json()
  const created=await request.post(`/api/projects/${project.id}/commands`,{data:{commands:[{type:"doc.create",args:{kind:"assembly",name:"Mechanism"}}]}})
  expect(created.ok()).toBe(true)
  const saved=await(await request.get(`/api/projects/${project.id}`)).json();const doc=saved.docs[0]
  await page.goto(`/#/p/${project.id}/${doc.id}`)
  await page.getByRole("button",{name:"Printed part…",exact:true}).click()
  await page.getByLabel("Name",{exact:true}).fill("Rotor plate")
  await page.getByRole("button",{name:"Create parametric part",exact:true}).click()
  await expect(page.locator(".assembly-item")).toHaveCount(1)
  await expect(page.locator(".assembly-mass")).toContainText("g")
  await page.getByRole("button",{name:"＋ Catalog part",exact:true}).click()
  await page.getByPlaceholder("Search mechanical parts, modules and components…").fill("socket screw")
  await page.getByText("M3 × 8 socket screw",{exact:true}).click()
  await expect(page.locator(".assembly-item")).toHaveCount(2)
  await expect(page.locator(".assembly-inspector")).toContainText("Part family dimensions")
  await page.getByRole("combobox",{name:"This anchor",exact:true}).selectOption("shoulder")
  await page.getByRole("combobox",{name:"Target anchor",exact:true}).selectOption("mounting_holes.h1")
  await page.getByLabel("Spacing (mm)",{exact:true}).fill("0")
  await page.getByRole("button",{name:"Fasten anchors",exact:true}).click()
  await expect(page.locator(".assembly-item").nth(1)).toContainText("mounted to item1")
  const before=await(await request.get(`/api/projects/${project.id}/assembly/${doc.id}/properties`)).json()
  expect(before.instances[1].mount.target).toBe("item1")
  await page.getByLabel("Size (mm) Z",{exact:true}).fill("15")
  await page.getByRole("button",{name:"Apply configuration",exact:true}).click()
  await expect.poll(async()=>{const result=await(await request.get(`/api/projects/${project.id}/assembly/${doc.id}/properties`)).json();return result.instances[1].localBounds.size[2]}).toBeCloseTo(15)
  await page.locator(".assembly-item").first().click()
  await page.getByLabel("Position (mm) X",{exact:true}).fill("20")
  await page.getByRole("button",{name:"Apply pose",exact:true}).click()
  await expect.poll(async()=>{const result=await(await request.get(`/api/projects/${project.id}/assembly/${doc.id}/properties`)).json();return result.instances[1].position[0]-before.instances[1].position[0]}).toBeCloseTo(20)
  await page.getByRole("button",{name:"Check interference",exact:true}).click()
  await expect(page.locator(".assembly-checks")).toBeVisible()
  await expect(page.locator(".assembly-checks")).not.toHaveAttribute("data-loading","true")
  await page.screenshot({path:testInfo.outputPath("mechanical-assembly.png")})
  const download=page.waitForEvent("download");await page.getByRole("button",{name:"3MF",exact:true}).click()
  expect((await download).suggestedFilename()).toBe("Mechanism.3mf")
  const latest=await(await request.get(`/api/projects/${project.id}`)).json()
  expect(latest.components).toHaveLength(1)
  expect(latest.components[0].props["physical.size.z"]).toBe("15")
  await page.reload();await expect(page.locator(".assembly-item")).toHaveCount(2)
  expect(errors).toEqual([])
})

test("CAD face sketches, editable splines and 3MF work in the browser",async({page,request},testInfo)=>{
  const errors:string[]=[];page.on("pageerror",error=>errors.push(error.message))
  const project=await(await request.post("/api/projects",{data:{name:"Face sketch acceptance"}})).json()
  const seeded=await request.post(`/api/projects/${project.id}/commands`,{data:{commands:[{type:"doc.create",args:{kind:"part-studio",name:"Face part",data:{features:[{id:"base",type:"sketch",entities:[{id:"r",type:"rectangle",width:40,height:30}]},{id:"body",type:"extrude",sketch:"base",depth:10}]}}}]}})
  expect(seeded.ok()).toBe(true)
  const saved=await(await request.get(`/api/projects/${project.id}`)).json();const doc=saved.docs[0]
  await page.goto(`/#/p/${project.id}/${doc.id}`)
  await expect(page.getByRole("button",{name:"Export STL",exact:true})).toBeEnabled()
  await page.getByRole("button",{name:"Sketch on face",exact:true}).click()
  const canvas=page.locator(".cad-viewport canvas");const box=await canvas.boundingBox();if(!box)throw new Error("No CAD canvas")
  const scale=Math.min(box.width,box.height)*.39/(Math.sqrt(40**2+30**2+10**2)/2)
  await canvas.click({position:{x:box.width/2,y:box.height/2-5*Math.sin(Math.PI/3)*scale}})
  await expect(page.locator(".cad-inspector")).toContainText("On picked face of body")
  await page.getByRole("combobox",{name:"Profile",exact:true}).selectOption("spline")
  await page.getByLabel("Spline points",{exact:true}).fill("-8, -6\n8, -6\n8, 6\n-8, 6")
  await page.getByRole("button",{name:"Create sketch",exact:true}).click()
  await expect(page.locator(".cad-feature")).toHaveCount(3)
  await page.locator(".cad-toolbar").getByRole("button",{name:"Extrude",exact:true}).click()
  await page.getByRole("combobox",{name:"Operation",exact:true}).selectOption("add")
  await page.getByLabel("Depth (mm)",{exact:true}).fill("5")
  await page.locator(".cad-inspector").getByRole("button",{name:"Extrude",exact:true}).click()
  await expect(page.locator(".cad-material")).toContainText("40 × 30 × 15 mm")
  await expect(page.locator(".cad-error")).toHaveCount(0)
  await page.screenshot({path:testInfo.outputPath("face-spline-cad.png")})
  const download=page.waitForEvent("download");await page.getByRole("button",{name:"3MF",exact:true}).click()
  expect((await download).suggestedFilename()).toBe("Face-part.3mf")
  const current=await(await request.get(`/api/projects/${project.id}`)).json()
  expect(current.docs[0].data.features[2].face.body).toBe("body")
  expect(current.docs[0].data.features[2].entities[0].type).toBe("spline")
  expect(errors).toEqual([])
})
